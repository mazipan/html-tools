// Generates the FAQ, More tools, and JSON-LD blocks into src/*.html so they
// are visible in `npm run dev` and bundled like the rest of the markup. Re-run
// whenever src/tools.json changes (new tool, edited FAQ, etc.):
//
//   npm run generate:sections
//
// Each block is wrapped in BEGIN/END HTML comments so re-runs replace the
// existing region in place instead of appending. First-run insertion points:
//   - FAQ + More tools  → immediately before <footer
//   - JSON-LD           → immediately before </head>
//
// No other build-time concern lives here — Parcel orchestration, build-time
// replacements (e.g. __BUILD_TIME__), redirects, and the sitemap all stay in
// scripts/build.mjs.

import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';
import { glob } from 'fs/promises';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const srcDir = resolve(root, 'src');

const log = (...args) => console.log('[generate-sections]', ...args);

const tools = JSON.parse(readFileSync(resolve(srcDir, 'tools.json'), 'utf8'));
const SITE = tools.site;
const SITE_URL = SITE.url;
const SITE_HOME = `${SITE_URL}/`;

// Pages that are routable for direct visits but excluded from the marketing
// surface — no FAQ, no cross-tool block, no JSON-LD. The source of truth is
// the `internal: true` flag on a tool entry in tools.json; the matching
// filter in scripts/build.mjs (sitemap, _redirects) reads the same flag.
const INTERNAL_PAGES = new Set(
  tools.tools.filter(t => t.internal).map(t => `${t.slug}.html`),
);

const escHtml = s =>
  String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const GENERATED_NOTE = 'generated by scripts/generate-sections.mjs — re-run after editing tools.json';

function wrapBlock(name, indent, innerLines) {
  const inner = innerLines.map(l => `${indent}${l}`).join('\n');
  return `${indent}<!-- BEGIN:${name} ${GENERATED_NOTE} -->\n${inner}\n${indent}<!-- END:${name} -->`;
}

function faqInnerLines(tool) {
  if (!tool.faqs?.length) return null;
  const items = tool.faqs.flatMap(({ q, a }) => [
    `    <details class="disclosure">`,
    `      <summary>${escHtml(q)}</summary>`,
    `      <div class="disclosure-content"><div class="disclosure-body">${escHtml(a)}</div></div>`,
    `    </details>`,
  ]);
  return [
    `<section class="max-w-[${tool.maxWidth || '1100px'}] mx-auto w-full px-6 py-8 border-t border-gray-800">`,
    `  <h2 class="text-xl font-bold text-white mb-6">FAQ</h2>`,
    `  <div class="space-y-2">`,
    ...items,
    `  </div>`,
    `</section>`,
  ];
}

function moreToolsInnerLines(current) {
  const others = tools.tools.filter(t => t.slug !== current.slug && !t.internal);
  // Preserve first-appearance order from tools.json for both categories
  // and the tools within each category.
  const byCategory = new Map();
  for (const t of others) {
    const cat = t.category || 'Other';
    if (!byCategory.has(cat)) byCategory.set(cat, []);
    byCategory.get(cat).push(t);
  }
  const groups = [...byCategory.entries()].flatMap(([cat, list]) => {
    if (!list.length) return [];
    const links = list.map(
      t =>
        `        <a href="/${t.slug}" class="text-sm text-gray-300 hover:text-blue-400 transition-colors no-underline">${t.icon} ${escHtml(t.name)}</a>`,
    );
    return [
      `    <div>`,
      `      <h3 class="text-xs font-semibold uppercase tracking-wider text-gray-500 mb-2">${escHtml(cat)}</h3>`,
      `      <div class="flex flex-wrap gap-x-5 gap-y-2">`,
      ...links,
      `      </div>`,
      `    </div>`,
    ];
  });
  return [
    `<section class="max-w-[${current.maxWidth || '1100px'}] mx-auto w-full px-6 py-8 border-t border-gray-800">`,
    `  <h2 class="text-xl font-bold text-white mb-6">More tools</h2>`,
    `  <div class="space-y-4">`,
    ...groups,
    `  </div>`,
    `</section>`,
  ];
}

function jsonLdObjects(filename) {
  if (filename === 'index.html') {
    return [
      {
        '@context': 'https://schema.org',
        '@type': 'WebSite',
        name: SITE.name,
        url: SITE_HOME,
        description: SITE.description,
        publisher: {
          '@type': 'Person',
          name: SITE.publisher.name,
          url: SITE.publisher.url,
        },
      },
    ];
  }
  const slug = filename.replace(/\.html$/, '');
  const tool = tools.tools.find(t => t.slug === slug);
  if (!tool) return [];
  const toolUrl = `${SITE_URL}/${tool.slug}`;
  const blocks = [
    {
      '@context': 'https://schema.org',
      '@type': 'WebApplication',
      name: tool.name,
      url: toolUrl,
      description: tool.description,
      applicationCategory: 'DeveloperApplication',
      operatingSystem: 'Any',
      browserRequirements: 'Requires JavaScript',
      offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' },
      isPartOf: { '@type': 'WebSite', name: SITE.name, url: SITE_HOME },
    },
    {
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: SITE.name, item: SITE_HOME },
        { '@type': 'ListItem', position: 2, name: tool.name, item: toolUrl },
      ],
    },
  ];
  if (tool.faqs?.length) {
    blocks.push({
      '@context': 'https://schema.org',
      '@type': 'FAQPage',
      mainEntity: tool.faqs.map(({ q, a }) => ({
        '@type': 'Question',
        name: q,
        acceptedAnswer: { '@type': 'Answer', text: a },
      })),
    });
  }
  return blocks;
}

function jsonLdInnerLines(filename) {
  const objs = jsonLdObjects(filename);
  if (!objs.length) return null;
  return objs.map(o => `<script type="application/ld+json">${JSON.stringify(o)}</script>`);
}

// Find the first match of `anchorRegex` and return the indent of the line it
// sits on, plus the offset of that line's start. Used so inserted blocks pick
// up the same indent as their anchor (`<footer` / `</head>`).
function locateAnchor(source, anchorRegex) {
  const m = source.match(anchorRegex);
  if (!m) return null;
  const lineStart = source.lastIndexOf('\n', m.index - 1) + 1;
  const indent = source.slice(lineStart, m.index).match(/^[ \t]*/)[0];
  return { lineStart, indent };
}

function applySection({ source, name, innerLines, anchorRegex, childOfAnchor = false }) {
  const blockRe = new RegExp(
    `([ \\t]*)<!-- BEGIN:${name}\\b[^>]*-->[\\s\\S]*?<!-- END:${name} -->\\n?`,
  );
  const existing = source.match(blockRe);

  if (existing) {
    const block = wrapBlock(name, existing[1], innerLines);
    return source.replace(blockRe, `${block}\n`);
  }

  const loc = locateAnchor(source, anchorRegex);
  if (!loc) {
    throw new Error(`scripts/generate-sections.mjs: anchor ${anchorRegex} not found`);
  }
  // Children of <head> sit one indent level deeper than </head> itself.
  const indent = childOfAnchor ? `${loc.indent}  ` : loc.indent;
  const block = wrapBlock(name, indent, innerLines);
  return `${source.slice(0, loc.lineStart)}${block}\n\n${source.slice(loc.lineStart)}`;
}

const files = (await Array.fromAsync(glob('*.html', { cwd: srcDir })))
  .filter(f => !f.startsWith('google'))
  .sort();

let touched = 0;
const skipped = [];

for (const file of files) {
  if (INTERNAL_PAGES.has(file)) {
    skipped.push(`${file} (internal)`);
    continue;
  }
  const filePath = resolve(srcDir, file);
  const original = readFileSync(filePath, 'utf8');
  let next = original;

  const ld = jsonLdInnerLines(file);
  if (ld) {
    next = applySection({
      source: next,
      name: 'json-ld',
      innerLines: ld,
      anchorRegex: /<\/head>/,
      childOfAnchor: true,
    });
  }

  if (file !== 'index.html') {
    const slug = file.replace(/\.html$/, '');
    const tool = tools.tools.find(t => t.slug === slug);
    if (tool) {
      const faq = faqInnerLines(tool);
      if (faq) {
        next = applySection({
          source: next,
          name: 'faq',
          innerLines: faq,
          anchorRegex: /<footer\b/,
        });
      }
      next = applySection({
        source: next,
        name: 'more-tools',
        innerLines: moreToolsInnerLines(tool),
        anchorRegex: /<footer\b/,
      });
    } else {
      skipped.push(`${file} (not in tools.json)`);
      continue;
    }
  }

  if (next !== original) {
    writeFileSync(filePath, next);
    touched++;
    log(`✏️  ${file}`);
  } else {
    log(`✓ ${file} (no changes)`);
  }
}

log(
  `🎉 wrote ${touched} file${touched === 1 ? '' : 's'}` +
    (skipped.length ? ` (skipped: ${skipped.join(', ')})` : ''),
);
